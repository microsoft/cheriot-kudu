#!/usr/bin/env python3
# Extract Sail spec functions (plus their dependencies) that extracted.sv
# lacks from ibexspec.sv, so harness code can call them outside the spec
# module. Usage: gen_ext_bounds.py > ext_bounds.sv
import os, re, sys
T=os.environ.get('SPEC_OUT','/home/scratch/fortress/kunyanliu/e2e_tools/upstream_spec/out')+'/'
src=open(T+'ibexspec.sv').read().split('\n')
have=set(re.findall(r'^function automatic \S+(?: \[[^\]]*\])? (\w+)\(',open(T+'extracted.sv').read(),re.M))
funcs={}; i=0
while i<len(src):
    m=re.match(r'\s*function automatic .*?(\w+)\(',src[i])
    if m:
        j=i
        while not re.match(r'\s*endfunction',src[j]): j+=1
        funcs[m.group(1)]='\n'.join(s[4:] if s.startswith('    ') else s for s in src[i:j+1]); i=j
    i+=1
want=sys.argv[1:] or ['getCapBounds','getCapPerms']; out=[]; seen=set()
def visit(f):
    if f in seen or f in have: return
    seen.add(f)
    body=funcs[f]
    for c in set(re.findall(r'\b(\w+)\(',body)):
        if c in funcs and c!=f: visit(c)
    out.append(f)
for w in want: visit(w)
print('// deps:',out,file=sys.stderr)
print('// Generated by gen_ext_bounds.py from ibexspec.sv; do not edit.')
for f in out:
    print(funcs[f]); print()
