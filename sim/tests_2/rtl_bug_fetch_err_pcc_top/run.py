"""rtl_bug_fetch_err_pcc_top directed test.

Reproduces KUDU-070: a fetch bus error 2-3 bytes below the PCC top is reported
as a PCC bounds fault (mcause 0x1c, MEPCC untagged) instead of an instruction
access fault.

The program (generated by the round-4 front-end review, gen_pcc.py) runs 54
PCC fetch-bounds cases at PMODE=1: each case jumps, through a capability whose
top T sits just after a short instruction sequence, into code at T-2/T-4/T/...
reached sequentially, by loops, jumps, branches, mret, etc. The trap handler
records count, mcause, mtval, MEPCC address/tag/base/length and the number of
instructions executed (t1). Each case prints
"PASS|FAIL <i> <name> n= c= v= pc= x= T= tag= b= l= t1=", then
"PCC FETCH PASS|FAIL failures=N cases=54".

Runs (all simv +PMODE=1):
  noerr  no bus error: every case must take the expected PCC bounds fault
         (mcause 0x1c, mtval 0x401; the J*@S-2 cases trap on the harness cjr
         with a c14 tag violation, mtval 0x1c2) -> "PCC FETCH PASS".
  err<c> +INSTR_ERR_ADDR on a 64-bit fetch word holding an in-bounds parcel
         of case <c>'s faulting instruction, built with FETCH_ERR_CASE=<c>:
         case <c> must take an instruction access fault (mcause 1, MEPCC tag
         kept, mtval = the errored parcel: pc, or pc+2 when only the second
         parcel of a 32-bit instruction errors). Sail rule: check pc+2 <= T,
         fetch parcel 1, then for a 32-bit instruction check pc+4 <= T and
         fetch parcel 2.
           err1   A32@T-2: 32-bit at T-2, first parcel errors. HEAD decodes
                  the errored garbage as 32-bit and reports 0x1c (KUDU-070).
           err5   Bc@T-2: 16-bit at T-2 (control; HEAD passes).
           err9   C32@T-4: 32-bit at T-4 straddling two words, only the
                  second parcel errors -> mtval pc+2 (ferr2w path).
           err37  Hentry32@T-2: entered directly at a 32-bit at T-2 (KUDU-070).
           err38  Hentryc@T-2: entered directly at a 16-bit at T-2.
  bnd<c> the same with FETCH_ERR_BOUNDS=1: the errored word is at/after T,
         so the bounds fault must still win (normal case outcome):
           bnd0, bnd37  32-bit at T-2 straddling into an errored word
                        (ferr2w: the pc+4 check still applies).
           bnd32 jal, bnd34 branch to T+2, bnd35 cjr to T+4, bnd36 cjal,
           bnd39 direct entry at T: the target word itself errors (the
                        bounds check must not be waived by fetch_err).
ERR_RUNS holds the fetch-word addresses (see the .dis). FETCH_ERR_* are
.data globals, so all builds share one .text layout; if it changes, the
program prints "FETCH ERR SETUP FAIL" (unmapped failure) until they are
updated.

Expected on HEAD: noerr, err5, err9, err38, bnd* PASS; err1, err37 XFAIL
(KUDU-070, Open). Fixed RTL: all PASS.

Run from anywhere: ./run.py [--build <dir with simv/simv32>] [--work <new dir>]
(see ../common/kudu_test.py and sim/testplan/direct_tests.md).
"""

import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "common"))
from kudu_test import Run, Test, main  # noqa: E402

ARGS = ["+PMODE=1", "+TIMEOUT=2000000"]
# (case, fetch word, expect bounds fault)
ERR_RUNS = [
    (1, "80001b98", False), (5, "80001c98", False), (9, "80001d98", False),
    (37, "80002488", False), (38, "800024c8", False),
    (0, "80001b58", True), (37, "80002490", True), (32, "80002350", True),
    (34, "800023d8", True), (35, "80002420", True), (36, "80002450", True),
    (39, "80002510", True),
]


def err_run(case, word, bounds):
    flav = "cheri+FETCH_ERR_CASE={}+FETCH_ERR_ADDR=0x{}".format(case, word)
    if bounds:
        flav += "+FETCH_ERR_BOUNDS=1"
    return Run("{}{}".format("bnd" if bounds else "err", case), "simv", flav,
               ARGS + ["+INSTR_ERR_ADDR=" + word], est=35)


TEST = Test(
    "rtl_bug_fetch_err_pcc_top",
    ["KUDU-070"],
    [Run("noerr", "simv", "cheri", ARGS, est=35)] +
    [err_run(*r) for r in ERR_RUNS],
    r"^PCC FETCH PASS failures=0 cases=54",
    [(r"^FAIL ([0-9]+) ", "KUDU-070")])

if __name__ == "__main__":
    sys.exit(main([TEST]))
