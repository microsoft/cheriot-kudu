"""rtl_bug_alt_tag_x test.

Reproduces KUDU-044: with the branch predictor off (cpuctrl.pdt_en = 0) the
ALT tag fields (alt_valid, alt_id) of the fetch outputs were undriven, so the
IR registers captured X and the issuer's ALT cancel/apply controls to
fetch_fifo64 were X.

The program (rv32 flavour, generated by gen_altstress.py --seed 104 in the
ALT review) runs a 32 KB straight-line/branch stress body many times while
toggling cpuctrl (CSR 0x7c0: predictor, ALT, RA prediction and const-fetch
bits). It compares a checksum per pass and prints "ALTSTRESS PASS fails=0"
(or "ALTSTRESS FAIL fails=N" with MISMATCH lines).

alt_chk.sv is bound into fetch_fifo64 (shadow build). It checks ALT
save/apply/cancel against a shadow of the instruction bus, and counts cycles
(after the first 8 cycles out of reset) where ex_alt_ctrl cancel/apply or the
alt_valid tag entering IR is X. The final block prints
"ALT_CHK FAIL KUDU-044 xcancel_cycles=.. xtag_cycles=.." for any X cycle,
"ALT_CHK FAIL errors=N" for checker errors, and "ALT_CHK PASS ..." otherwise.
Before the fix (f6dddaa) the conf1 simv32 run counted 1503 xcancel and 14318
xtag cycles. The pass verdict needs both ALTSTRESS PASS and ALT_CHK PASS.

Expected on HEAD: PASS (bug fixed).

Needs the checker, so the runner builds a shadow simv/simv32 in the work
directory (--build is not used).

Run from anywhere: ./run.py [--work <new dir>] (see ../common/kudu_test.py and
sim/testplan/direct_tests.md).
"""

import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
from kudu_test import Run, Shadow, Test, main  # noqa: E402

WS = ["+INSTR_GNT_WMAX=2", "+INSTR_RESP_WMAX=5", "+DATA_GNT_WMAX=3", "+DATA_RESP_WMAX=4"]
BASE = ["+TIMEOUT=4000000"]

TEST = Test(
    "rtl_bug_alt_tag_x", ["KUDU-044"],
    [Run("rv32", "simv32", "rv32", BASE, est=20),
     Run("rv32_ws", "simv32", "rv32", BASE + WS, est=30),
     Run("pmode0", "simv", "rv32", ["+PMODE=0"] + BASE, est=20)],
    r"(?s)^ALTSTRESS PASS fails=.*^ALT_CHK PASS",
    [(r"ALT_CHK FAIL KUDU-044 ", "KUDU-044")],
    shadow=Shadow(extra=[HERE / "alt_chk.sv"]))

if __name__ == "__main__":
    sys.exit(main([TEST]))
