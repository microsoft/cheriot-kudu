"""rtl_bug_rvfi_intr_stale_pc directed test.

Reproduces KUDU-074: the RVFI record of a taken interrupt (intr=1) reports
the pc/insn of IR0 even when IR0 is not valid (rtl/tracer.sv uses
ir0_dec.pc/insn, while the core saves mepc = ir0_nxt_pc_q in that case), so
after an mret/dret/fence.i flush or once IR0 has drained the record carries a
stale pc, e.g. an instruction that has already retired. Architectural state
(mepc) is correct; only the trace is wrong. Only pc_rdata is checked: insn,
pc_wdata and the mem masks of an interrupt record are don't-care.

The program is the round-6 LSU/interrupt stress program lsc_179 (generated by
gen_lsc.py, seed 179): a random CHERIoT load/store stream at PMODE=1 under
random interrupts and random bus errors. Its ISR (in .text.isr below
0x80001000, see link_test.ld, so random bus errors never hit it) acks every
interrupt and returns with mret, leaving mepc unchanged.

The stock non-DII testbench does not write rvfi_kudu_core.log
(RvfiDumpEn = 0), so the test runs on a shadow build with rvfi_dump.patch
(RvfiDumpEn = 1). The post hook intr_pc_check.py compares the pc of every
interrupt record with the pc the handler's mret returns to (= mepc) and
prints "FAIL intr-pc ..." per stale record, then
"RVFI INTR PC PASS checked=N" or "RVFI INTR PC SUMMARY FAIL stale=K checked=N".

Runs (simv +PMODE=1, original reproducer plusargs; the original +DBGROM is
dropped, since there are no debug requests):
  err    +INTR_RATE=4 with random fetch/data bus errors (seed 639343581).
  noerr  the same without bus errors.

Expected on HEAD: both XFAIL (KUDU-074, Open).

Run from anywhere: ./run.py [--build <dir>] [--work <new dir>] (the shadow
build is compiled into the work directory; see ../common/kudu_test.py and
sim/testplan/direct_tests.md).
"""

import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "common"))
sys.path.insert(0, str(HERE))
from kudu_test import Run, Shadow, Test, main  # noqa: E402
import intr_pc_check  # noqa: E402

ARGS = ["+PMODE=1", "+TIMEOUT=1000000", "+INTR_RATE=4",
        "+INSTR_GNT_WMAX=3", "+INSTR_RESP_WMAX=15", "+DATA_GNT_WMAX=10", "+DATA_RESP_WMAX=7",
        "+ntb_random_seed=639343581"]

TEST = Test(
    "rtl_bug_rvfi_intr_stale_pc",
    ["KUDU-074"],
    [Run("err", "simv", "cheri", ARGS + ["+INSTR_ERR_RATE=5", "+DATA_ERR_RATE=5"], est=30),
     Run("noerr", "simv", "cheri", ARGS, est=30)],
    r"^RVFI INTR PC PASS checked=[1-9]",
    [(r"^FAIL intr-pc ", "KUDU-074")],
    shadow=Shadow(patches=[HERE / "rvfi_dump.patch"]),
    post=intr_pc_check.check)

if __name__ == "__main__":
    sys.exit(main([TEST]))
